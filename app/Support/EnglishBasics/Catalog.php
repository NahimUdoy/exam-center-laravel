    public static function lessons(): array
    {
        $order = 0;
        $out = [];

        foreach (self::raw() as $row) {
            $drills = [];
            foreach ($row['drills'] as $i => $drill) {
                $drills[] = self::mapDrill($drill, $i);
            }

            $out[] = [
                'slug' => $row['slug'],
                'letter' => $row['letter'],
                'category' => $row['category'],
                'title' => $row['title'],
                'subtitle' => $row['subtitle'],
                'level' => $row['level'],
                'sort_order' => $order++,
                'summary' => $row['summary'],
                'body' => $row['body'],
                'rules' => $row['rules'],
                'examples' => $row['examples'],
                'drills' => $drills,
            ];
        }

        return $out;
    }

    private static function mapDrill(array $drill, int $i): array
    {
        $hasSentence = isset($drill[1]) && is_string($drill[1]);

        if ($hasSentence) {
            return [
                'kind' => 'mcq',
                'prompt' => $drill[0],
                'sentence' => $drill[1],
                'options' => $drill[2],
                'correct' => $drill[3],
                'explanation' => $drill[4],
                'sort_order' => $i,
            ];
        }

        return [
            'kind' => 'mcq',
            'prompt' => $drill[0],
            'sentence' => self::sentenceFromPrompt($drill[0]),
            'options' => $drill[1],
            'correct' => $drill[2],
            'explanation' => $drill[3],
            'sort_order' => $i,
        ];
    }

    private static function sentenceFromPrompt(string $prompt): ?string
    {
        if (preg_match('/[“"]([^”"]{6,})[”"]/u', $prompt, $m)) {
            return $m[1];
        }

        return null;
    }

