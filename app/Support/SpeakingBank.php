    /**
     * @param  list<string>  $tags
     * @return array{topic: string, text: string, bullets: list<string>, tags: list<string>}
     */
    private static function card(string $topic, string $shouldSay, array $tags): array
    {
        $bullets = collect(preg_split('/,\s*|\band explain\s+/i', $shouldSay) ?: [])
            ->map(fn ($part) => trim((string) $part, " ."))
            ->filter()
            ->take(4)
            ->values()
            ->all();

        return [
            'topic' => $topic,
            'text' => 'Describe '.lcfirst($topic).'. You should say '.$shouldSay.'.',
            'bullets' => $bullets ?: ['What it is', 'When it happened', 'What you did', 'Why it matters'],
            'tags' => $tags,
        ];
    }
