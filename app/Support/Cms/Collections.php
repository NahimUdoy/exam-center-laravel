    public static function all(): array
    {
        return config('cms.collections', self::definitions());
    }

    public static function get(string $key): ?array
    {
        foreach (self::definitions() as $item) {
            if ($item['key'] === $key || $item['path'] === $key) {
                return $item;
            }
        }

        return null;
    }

    public static function nav(): array
    {
        return array_map(fn ($c) => [
            'href' => '/admin/'.$c['path'],
            'label' => $c['label'],
            'icon' => $c['icon'],
            'key' => $c['key'],
        ], self::definitions());
    }

